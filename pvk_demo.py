def simulate_feedback(
    summary: DataSummary, recommendations: list[Recommendation]
) -> dict[str, Any]:
    best = summary.best_pce
    if recommendations:
        simulated_best = round(best + min(0.4, 0.1 + recommendations[0].mock_acquisition_score / 10), 2)
    else:
        simulated_best = best
    return {
        "rounds": ["Initial data", "Recommended batch", "Simulated feedback"],
        "best_so_far": [best, best, simulated_best],
        "uncertainty_label": ["mixed literature data", "next batch proposed", "synthetic result"],
        "caption": "Synthetic walkthrough only. Not experimental validation and not an algorithm benchmark.",
    }


def _fixed_process(row: dict[str, Any]) -> dict[str, Any]:
    return {
        "solvent": row.get("solvent") or "IPA",
        "spin_speed_rpm": _safe_int(row.get("spin_speed_rpm"), default=4000),
        "spin_time_s": _safe_int(row.get("spin_time_s"), default=30),
        "anneal_temp_C": _safe_int(row.get("anneal_temp_C"), default=100),
        "anneal_time_min": _safe_int(row.get("anneal_time_min"), default=5),
    }


def _standard_steps() -> list[str]:
    return [
        "Prepare the passivation solution using the stated demo formulation.",
        "Spin-coat the passivation solution on the perovskite film under the fixed demo process.",
        "Anneal under the stated demo condition.",
        "Complete downstream transport layers and electrodes according to the baseline process.",
        "Measure PCE, Voc, Jsc, FF, and capture qualitative film observations.",
    ]


def _top_records(data: pd.DataFrame, passivator: str, limit: int = 2) -> list[str]:
    column = f"has_{passivator}"
    if column not in data.columns or "PCE" not in data.columns:
        return []
    subset = data[pd.to_numeric(data[column], errors="coerce").fillna(0) > 0]
    subset = subset.sort_values("PCE", ascending=False)
    return [str(record_id) for record_id in subset["experiment_id"].head(limit).tolist()]


def _normalize_dataframe(data: pd.DataFrame) -> pd.DataFrame:
    normalized = data.copy()
    if "PCE" not in normalized.columns and "PCE_percent" in normalized.columns:
        normalized["PCE"] = pd.to_numeric(normalized["PCE_percent"], errors="coerce")
    if "passivator_system" not in normalized.columns:
        normalized["passivator_system"] = normalized.get("passivator_combo", "Not specified")
    if "data_type" not in normalized.columns:
        normalized["data_type"] = "unknown"
    for passivator in PASSIVATORS:
        column = f"has_{passivator}"
        if column not in normalized.columns:
            normalized[column] = 0
        normalized[column] = pd.to_numeric(normalized[column], errors="coerce").fillna(0)
    return normalized


def _safe_float(value: Any, default: float = 0.0) -> float:
    try:
        if pd.isna(value):
            return default
        return float(value)
    except (TypeError, ValueError):
        return default


def _safe_int(value: Any, default: int) -> int:
    try:
        if pd.isna(value):
            return default
        return int(float(value))
    except (TypeError, ValueError):
        return default
