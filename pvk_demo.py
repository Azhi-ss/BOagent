@dataclass(frozen=True)
class PipelineStage:
    name: str
    responsibility: str
    output_summary: str


@dataclass(frozen=True)
class DataSummary:
    total_records: int
    best_pce: float
    mean_pce: float
    best_experiment: dict[str, Any]
    passivator_counts: dict[str, int]
    data_type_counts: dict[str, int]
    pipdi_real_sample_count: int
    data_health_notes: list[str]


@dataclass(frozen=True)
class Recommendation:
    experiment_id: str
    recommendation_type: str
    passivator_combination: str
    process: dict[str, Any]
    mock_acquisition_score: float
    supporting_records: list[str]
    evidence_level: str
    data_boundary: str
    reason: str
    risk_level: str
    risks: list[str]
    hypothesis: str
    validation_required: bool
    steps: list[str]
    observations: list[str]


