def load_experiment_data(path: str | Path = DEFAULT_DATA_PATH) -> pd.DataFrame:
    """Load the demo CSV and normalize the current extracted schema."""
    data = pd.read_csv(path)
    normalized = data.copy()

    if "PCE" not in normalized.columns and "PCE_percent" in normalized.columns:
        normalized["PCE"] = pd.to_numeric(normalized["PCE_percent"], errors="coerce")

    if "passivator_system" not in normalized.columns:
        if "passivator_combo" in normalized.columns:
            normalized["passivator_system"] = normalized["passivator_combo"].fillna(
                "Not specified"
            )
        else:
            normalized["passivator_system"] = "Not specified"

    for passivator in PASSIVATORS:
        column = f"has_{passivator}"
        if column not in normalized.columns:
            normalized[column] = 0
        normalized[column] = pd.to_numeric(normalized[column], errors="coerce").fillna(0)

    if "data_type" not in normalized.columns:
        normalized["data_type"] = "unknown"

    if "evidence_text" not in normalized.columns:
        normalized["evidence_text"] = ""

    return normalized


def build_data_summary(data: pd.DataFrame) -> DataSummary:
    data = _normalize_dataframe(data)
    total_records = int(len(data))
    if total_records == 0:
        return DataSummary(
            total_records=0,
            best_pce=0.0,
            mean_pce=0.0,
            best_experiment={},
            passivator_counts={passivator: 0 for passivator in PASSIVATORS},
            data_type_counts={},
            pipdi_real_sample_count=0,
            data_health_notes=["No records loaded. Use the bundled demo CSV to run the demo."],
        )

    pce = pd.to_numeric(data.get("PCE", pd.Series(dtype=float)), errors="coerce")
    best_index = pce.idxmax() if pce.notna().any() else data.index[0]
    best_row = data.loc[best_index].to_dict()
    best_pce = _safe_float(best_row.get("PCE"))

    passivator_counts = {
        passivator: int(pd.to_numeric(data[f"has_{passivator}"], errors="coerce").fillna(0).sum())
        for passivator in PASSIVATORS
    }
    data_type_counts = {
        str(data_type): int(count)
        for data_type, count in data["data_type"].fillna("unknown").value_counts().items()
    }
    pipdi_real_sample_count = int(
        data[
            (pd.to_numeric(data["has_PipDI"], errors="coerce").fillna(0) > 0)
            & (data["data_type"] != "simulated_for_demo")
        ].shape[0]
    )

    notes = [
        f"Loaded {total_records} demo records from the structured CSV.",
        "PCE values are literature-extracted or manually curated demo evidence, not a controlled BO benchmark.",
    ]
    if pipdi_real_sample_count == 0:
        notes.append("PipDI has no real sample in the current dataset; treat it as demo-only exploration.")
    if "concentration_text" in data.columns:
        missing_or_text = data["concentration_text"].fillna("").astype(str).str.strip()
        if (missing_or_text == "").any() or missing_or_text.str.contains(r"[a-zA-Z]", regex=True).any():
            notes.append("Concentration values are mixed text units; P0 uses rules instead of real BO.")
    if "perovskite_system" in data.columns and len(data["perovskite_system"].dropna().unique()) > 1:
        notes.append("Records span multiple perovskite systems; avoid causal cross-system PCE claims.")

    return DataSummary(
        total_records=total_records,
        best_pce=round(best_pce, 2),
        mean_pce=round(float(pce.mean()) if pce.notna().any() else 0.0, 2),
        best_experiment=best_row,
        passivator_counts=passivator_counts,
        data_type_counts=data_type_counts,
        pipdi_real_sample_count=pipdi_real_sample_count,
        data_health_notes=notes,
    )


